import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = join(__dirname, "..", "..");
const ASSETS_DIR = join(ROOT_DIR, "assets");
const DIST_DIR = join(ROOT_DIR, "dist");

mkdirSync(ASSETS_DIR, { recursive: true });
mkdirSync(DIST_DIR, { recursive: true });

const rootIco = join(ROOT_DIR, "burgercord.ico");
const rootPng = join(ROOT_DIR, "burgercord.png");

if (existsSync(rootIco) && !existsSync(join(ASSETS_DIR, "burgercord.ico"))) {
    copyFileSync(rootIco, join(ASSETS_DIR, "burgercord.ico"));
}
if (existsSync(rootPng) && !existsSync(join(ASSETS_DIR, "burgercord.png"))) {
    copyFileSync(rootPng, join(ASSETS_DIR, "burgercord.png"));
}

for (const file of ["burgercord.ico", "burgercord.png", "burgercord-tray.png", "burgercord-tray-unread.png"]) {
    const src = join(ASSETS_DIR, file);
    if (existsSync(src)) {
        copyFileSync(src, join(DIST_DIR, file));
    }
}

const iconPngPath = join(ASSETS_DIR, "burgercord.png");
const trayPngPath = join(ASSETS_DIR, "burgercord-tray.png");
const trayUnreadPngPath = join(ASSETS_DIR, "burgercord-tray-unread.png");

const iconBase64 = existsSync(iconPngPath) ? readFileSync(iconPngPath).toString("base64") : "";
const trayBase64 = existsSync(trayPngPath) ? readFileSync(trayPngPath).toString("base64") : iconBase64;
const trayUnreadBase64 = existsSync(trayUnreadPngPath) ? readFileSync(trayUnreadPngPath).toString("base64") : iconBase64;

const tsOut = `/*
 * Burgercord, a high-performance & token-hardened Discord client mod
 * Copyright (c) 2026 Burgercord and contributors
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * AUTO-GENERATED BY scripts/build/generateIcons.mjs — Contains your official Burgercord icon assets
 */

export const BURGERCORD_NAME = "Burgercord";

export const BURGERCORD_ICON_BASE64 = "${iconBase64}";
export const BURGERCORD_ICON_DATA_URI = "data:image/png;base64,${iconBase64}";

export const BURGERCORD_TRAY_BASE64 = "${trayBase64}";
export const BURGERCORD_TRAY_DATA_URI = "data:image/png;base64,${trayBase64}";

export const BURGERCORD_TRAY_UNREAD_BASE64 = "${trayUnreadBase64}";
export const BURGERCORD_TRAY_UNREAD_DATA_URI = "data:image/png;base64,${trayUnreadBase64}";
`;

writeFileSync(join(ROOT_DIR, "src", "utils", "burgerIcon.ts"), tsOut, "utf-8");
console.log("[Burgercord] Generated src/utils/burgerIcon.ts and copied icon assets to dist/.");
